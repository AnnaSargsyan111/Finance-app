/** "2 տարում", "6 ամսում", "1 տարի 6 ամսում" */
export function durationHy(months: number): string {
  const y = Math.floor(months / 12);
  const m = months % 12;
  if (y === 0) return `${m} ամսում`;
  if (m === 0) return `${y} տարում`;
  return `${y} տարի ${m} ամսում`;
}
